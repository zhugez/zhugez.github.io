import { statSync, writeFileSync } from 'node:fs';

const sizes = Object.fromEntries(['a', 'b', 'c', 'd'].map(side => {
  const pathname = `/media/vinyl/adele-30-${side}.m4a`;
  return [pathname, statSync(new URL(`../public${pathname}`, import.meta.url)).size];
}));
writeFileSync(new URL('../src/media-sizes.ts', import.meta.url), `// Generated by scripts/prepare-media.mjs from the deployed audio files.\nexport const mediaSizes: Record<string, number> = ${JSON.stringify(sizes, null, 2)};\n`);
